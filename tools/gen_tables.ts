// boktai2 decomp のヘッダとソースから、ビューワが使う表を作る
// - names.ts: SpriteID, アニメファイルID, BG パレットのファイルID, スクリプトID, 文字列ID の定数名
//   タイルマップ・当たり判定マップのファイルID (include/constants/sprite.h, sprite_animation.h, include/bg_pltt.h, include/constants/script.h, strings.h, tilemap.h, collision_map.h)
// - aux_anims.ts: AuxSprite とアニメファイルの組 (ソース中で一緒に使われているもの)
// - bgpltt_refs.ts: BG パレットがソース中で読まれている場所
// - particle_refs.ts: パーティクルのグループと同じ関数で使われているアニメファイルと OBJ パレット, グループのポーズ名
// e.g. deno run --allow-read --allow-write tools/gen_tables.ts ~/Dev/GBA/ret/boktai2/boktai2

// BOKHASH (tools/hash.ts in boktai2 decomp), ここで使うのは ASCII だけ
const bokhash = (s: string): number => {
  let hash = 0;
  for (const byte of new TextEncoder().encode(s)) {
    hash = ((hash << 5) | (hash >>> 11)) & 0xFFFF;
    hash = (hash + byte) & 0xFFFF;
  }
  return hash;
};

const decomp = Deno.args[0];
if (!decomp) {
  console.error("usage: gen_tables.ts <boktai2 decomp dir>");
  Deno.exit(1);
}

const hex4 = (n: number) => `0x${n.toString(16).toUpperCase().padStart(4, "0")}`;

type Define = { name: string; id: number; desc: string };

// `#define NAME 0x1234 // desc` か `#define NAME BOKHASH("str") // desc` を拾う
const parseDefines = (src: string, prefix: RegExp): Define[] => {
  const defs: Define[] = [];
  for (const line of src.split("\n")) {
    const m = line.match(/^#define (\w+)\s+(0x[0-9A-Fa-f]+|BOKHASH\("([^"]+)"\))\s*(?:\/\/\s*(.*))?$/);
    if (!m || !prefix.test(m[1])) continue;
    const id = m[3] !== undefined ? bokhash(m[3]) : parseInt(m[2], 16);
    const desc = (m[4] ?? "").replace(/^0x[0-9A-Fa-f]{4}(,\s*|$)/, ""); // 値そのものの注記は除く
    defs.push({ name: m[1], id, desc });
  }
  return defs;
};

const sprites = parseDefines(await Deno.readTextFile(`${decomp}/include/constants/sprite.h`), /^SPRITE_/);
const anims = parseDefines(await Deno.readTextFile(`${decomp}/include/constants/sprite_animation.h`), /^ANI?M_/);
const bgPltts = parseDefines(await Deno.readTextFile(`${decomp}/include/bg_pltt.h`), /^BGP_/);
const tilemaps = parseDefines(await Deno.readTextFile(`${decomp}/include/constants/tilemap.h`), /^TILEMAP_/);
const collisions = parseDefines(await Deno.readTextFile(`${decomp}/include/constants/collision_map.h`), /^HP_/);
const strings = parseDefines(await Deno.readTextFile(`${decomp}/include/constants/strings.h`), /^(STR|BIN)_/);

// `#define Script_StaffRoll Script_0x1040 // desc` を拾う
const scriptNames: Define[] = [];
for (const line of (await Deno.readTextFile(`${decomp}/include/constants/script.h`)).split("\n")) {
  const m = line.match(/^#define (Script_\w+)\s+Script_0x([0-9A-Fa-f]+)\s*(?:\/\/\s*(.*))?$/);
  if (m) scriptNames.push({ name: m[1], id: parseInt(m[2], 16), desc: m[3] ?? "" });
}

// 同じIDに複数の名前があれば先に書かれた方を採る
const nameTable = (defs: Define[]) => {
  const seen = new Set<number>();
  const lines: string[] = [];
  for (const d of defs) {
    if (seen.has(d.id)) continue;
    seen.add(d.id);
    lines.push(`  ${hex4(d.id)}: [${JSON.stringify(d.name)}, ${JSON.stringify(d.desc)}],`);
  }
  return lines.join("\n");
};

await Deno.writeTextFile(
  new URL("../names.ts", import.meta.url),
  `// This file is generated by tools/gen_tables.ts. Do not edit.

// SpriteID -> [定数名, 説明] (include/constants/sprite.h in boktai2 decomp)
export const SPRITE_NAMES: Record<number, [name: string, desc: string]> = {
${nameTable(sprites)}
};

// アニメファイルID (DIR_ANIMATION) -> [定数名, 説明] (include/constants/sprite_animation.h in boktai2 decomp)
export const ANIM_NAMES: Record<number, [name: string, desc: string]> = {
${nameTable(anims)}
};

// BG パレットのファイルID (DIR_BGPLTT) -> [定数名, 説明] (include/bg_pltt.h in boktai2 decomp)
export const BGP_NAMES: Record<number, [name: string, desc: string]> = {
${nameTable(bgPltts)}
};

// タイルマップのファイルID (DIR_TILE_MAP) -> [定数名, 説明] (include/constants/tilemap.h in boktai2 decomp)
export const TILEMAP_NAMES: Record<number, [name: string, desc: string]> = {
${nameTable(tilemaps)}
};

// 当たり判定マップのファイルID (DIR_COLLISION_MAP) -> [定数名, 説明] (include/constants/collision_map.h in boktai2 decomp)
export const COLLISION_NAMES: Record<number, [name: string, desc: string]> = {
${nameTable(collisions)}
};

// スクリプトID -> [名前, 説明] (include/constants/script.h in boktai2 decomp)
export const SCRIPT_NAMES: Record<number, [name: string, desc: string]> = {
${nameTable(scriptNames)}
};

// 文字列ID (StringRef) -> [定数名, 説明] (include/constants/strings.h in boktai2 decomp)
export const STRING_NAMES: Record<number, [name: string, desc: string]> = {
${nameTable(strings)}
};
`,
);

// --------------------------------------------
// AuxSprite とアニメファイルの組を拾う
// 1. 1行の中に SPRITE_* と ANIM_* の定数が両方ある (sPreviewModels の行, SpriteHolder_InitAux(...) など)
// 2. 同じ関数の中に Video_GetAuxSprite(_, X) と GetFile(DIR_ANIMATION, Y) が両方ある (X, Y は定数か16進数リテラル)

const spriteByName = new Map(sprites.map((d) => [d.name, d.id]));
const animByName = new Map(anims.map((d) => [d.name, d.id]));
const bgPlttByName = new Map(bgPltts.map((d) => [d.name, d.id]));
const resolve = (token: string, byName: Map<string, number>): number | undefined => {
  if (/^0x[0-9A-Fa-f]+$/.test(token)) return parseInt(token, 16);
  return byName.get(token);
};

const pairs = new Map<number, Map<number, string[]>>(); // spriteID -> animID -> 出現場所
const addPair = (sprite: number, anim: number, where: string) => {
  if (anim === 0) return;
  const m = pairs.get(sprite) ?? new Map<number, string[]>();
  pairs.set(sprite, m);
  const list = m.get(anim) ?? [];
  m.set(anim, list);
  if (!list.includes(where)) list.push(where);
};

const bgPlttRefs = new Map<number, string[]>(); // BG パレットのファイルID -> 読まれている場所
const addBgPlttRef = (id: number, where: string) => {
  const list = bgPlttRefs.get(id) ?? [];
  bgPlttRefs.set(id, list);
  if (!list.includes(where)) list.push(where);
};

// src/ 以下の .c (src/ からの相対パス)
const files: string[] = [];
const walk = async (dir: string) => {
  for await (const e of Deno.readDir(`${decomp}/src/${dir}`)) {
    const path = dir ? `${dir}/${e.name}` : e.name;
    if (e.isDirectory) await walk(path);
    else if (e.isFile && e.name.endsWith(".c")) files.push(path);
  }
};
await walk("");
files.sort();

for (const file of files) {
  const lines = (await Deno.readTextFile(`${decomp}/src/${file}`)).split("\n");

  // 1. 同じ行
  lines.forEach((line, i) => {
    const code = line.replace(/\/\/.*$/, "");
    const ss = [...code.matchAll(/\bSPRITE_\w+/g)].map((m) => spriteByName.get(m[0])).filter((v) => v !== undefined);
    const as = [...code.matchAll(/\bANI?M_\w+/g)].map((m) => animByName.get(m[0])).filter((v) => v !== undefined);
    for (const s of ss) for (const a of as) addPair(s, a, `${file}:${i + 1}`);

    // GetBgPlttFile(X) か GetFile(DIR_BGPLTT, X), X は定数か16進数リテラル
    for (const m of code.matchAll(/(?:GetBgPlttFile\(|GetFile\(DIR_BGPLTT,\s*)(\w+)\s*\)/g)) {
      const id = resolve(m[1], bgPlttByName);
      if (id !== undefined) addBgPlttRef(id, `${file}:${i + 1}`);
    }
  });

  // 2. 同じ関数, 行頭が `}` の行で関数の終わりとみなす
  let gfx: [number, number][] = []; // [spriteID, 行番号]
  let anm: [number, number][] = [];
  lines.forEach((line, i) => {
    const code = line.replace(/\/\/.*$/, "");
    for (const m of code.matchAll(/Video_GetAuxSprite\([^,]+,\s*(\w+)\s*\)/g)) {
      const id = resolve(m[1], spriteByName);
      if (id !== undefined) gfx.push([id, i + 1]);
    }
    for (const m of code.matchAll(/GetFile\(DIR_ANIMATION,\s*(\w+)\s*\)/g)) {
      const id = resolve(m[1], animByName);
      if (id !== undefined) anm.push([id, i + 1]);
    }
    if (line.startsWith("}")) {
      for (const [s, sl] of gfx) for (const [a, al] of anm) addPair(s, a, `${file}:${Math.min(sl, al)}`);
      gfx = [];
      anm = [];
    }
  });
}

const pairLines: string[] = [];
for (const s of [...pairs.keys()].sort((a, b) => a - b)) {
  const items = [...pairs.get(s)!.entries()].sort((a, b) => a[0] - b[0]).map(([a, where]) => `[${hex4(a)}, ${JSON.stringify(where.join(", "))}]`);
  pairLines.push(`  ${hex4(s)}: [${items.join(", ")}],`);
}

await Deno.writeTextFile(
  new URL("../aux_anims.ts", import.meta.url),
  `// This file is generated by tools/gen_tables.ts. Do not edit.

// SpriteID -> [アニメファイルID, ソース上で一緒に使われている場所][]
// ROM のデータからは決まらないので boktai2 decomp のソースから拾ったもの, MainSprite の ID が混ざることもある
export const AUX_ANIM_REFS: Record<number, [anim: number, where: string][]> = {
${pairLines.join("\n")}
};
`,
);

const refLines = [...bgPlttRefs.keys()].sort((a, b) => a - b).map((id) => `  ${hex4(id)}: ${JSON.stringify(bgPlttRefs.get(id)!.join(", "))},`);

await Deno.writeTextFile(
  new URL("../bgpltt_refs.ts", import.meta.url),
  `// This file is generated by tools/gen_tables.ts. Do not edit.

// BG パレットのファイルID -> ソース中で GetBgPlttFile(id) などで読まれている場所 (定数か16進数リテラルで書かれているものだけ)
export const BGPLTT_REFS: Record<number, string> = {
${refLines.join("\n")}
};
`,
);

// --------------------------------------------
// パーティクル
// グループID は include/particle.h の PTCL_GROUP_*, ポーズ名は include/constants/particle.h の // PTCL_GROUP_N の節ごと

const particleGroups = parseDefines(await Deno.readTextFile(`${decomp}/include/particle.h`), /^PTCL_GROUP_\d+$/);
const groupByName = new Map(particleGroups.map((d) => [d.name, d.id]));

// ポーズ名: `#define NAME N // desc` と `#define NAME(num) (B + (num)) // desc` (次の定義の手前まで NAME(0), NAME(1), ... と展開する)
const poseLines: string[] = [];
{
  type Pose = { idx: number; name: string; desc: string; macro: boolean };
  const sections = new Map<number, Pose[]>();
  let group: number | undefined;
  for (const line of (await Deno.readTextFile(`${decomp}/include/constants/particle.h`)).split("\n")) {
    const sec = line.match(/^\/\/\s*(PTCL_GROUP_\d+)/);
    if (sec) {
      group = groupByName.get(sec[1]);
      if (group !== undefined) sections.set(group, []);
      continue;
    }
    if (group === undefined) continue;
    const m = line.match(/^#define (\w+)\s+(\d+)\s*(?:\/\/\s*(.*))?$/);
    const f = line.match(/^#define (\w+)\((\w+)\)\s+\((\d+) \+ \(\2\)\)\s*(?:\/\/\s*(.*))?$/);
    if (m) sections.get(group)!.push({ idx: Number(m[2]), name: m[1], desc: m[3] ?? "", macro: false });
    else if (f) sections.get(group)!.push({ idx: Number(f[3]), name: f[1], desc: f[4] ?? "", macro: true });
  }
  for (const [g, poses] of sections) {
    poses.sort((a, b) => a.idx - b.idx);
    const items: string[] = [];
    poses.forEach((p, i) => {
      if (!p.macro) return items.push(`${p.idx}: [${JSON.stringify(p.name)}, ${JSON.stringify(p.desc)}]`);
      const end = poses[i + 1]?.idx ?? p.idx + 1; // 最後の関数形式マクロは1つだけ
      for (let k = p.idx; k < end; k++) items.push(`${k}: [${JSON.stringify(`${p.name}(${k - p.idx})`)}, ${JSON.stringify(p.desc)}]`);
    });
    poseLines.push(`  ${hex4(g)}: { ${items.join(", ")} },`);
  }
}

// 同じ関数の中の GetParticleGroup(X) と GetFile(DIR_ANIMATION, Y) / Particle_SetPltt(_, Z)
const ptclAnims = new Map<number, Map<number, string[]>>();
const ptclPltts = new Map<number, Map<number, string[]>>();
const addTo = (table: Map<number, Map<number, string[]>>, g: number, v: number, where: string) => {
  const m = table.get(g) ?? new Map<number, string[]>();
  table.set(g, m);
  const list = m.get(v) ?? [];
  m.set(v, list);
  if (!list.includes(where)) list.push(where);
};
for (const file of files) {
  const lines = (await Deno.readTextFile(`${decomp}/src/${file}`)).split("\n");
  let groups: number[] = [];
  let anm: [number, number][] = [];
  let pltt: [number, number][] = [];
  lines.forEach((line, i) => {
    const code = line.replace(/\/\/.*$/, "");
    for (const m of code.matchAll(/GetParticleGroup\(\s*(\w+)\s*\)/g)) {
      const id = resolve(m[1], groupByName);
      if (id !== undefined && !groups.includes(id)) groups.push(id);
    }
    for (const m of code.matchAll(/GetFile\(DIR_ANIMATION,\s*(\w+)\s*\)/g)) {
      const id = resolve(m[1], animByName);
      if (id !== undefined) anm.push([id, i + 1]);
    }
    for (const m of code.matchAll(/Particle_SetPltt\([^,]+,\s*(\d+)\s*\)/g)) pltt.push([Number(m[1]), i + 1]);
    if (line.startsWith("}")) {
      for (const g of groups) {
        for (const [a, l] of anm) addTo(ptclAnims, g, a, `${file}:${l}`);
        for (const [p, l] of pltt) addTo(ptclPltts, g, p, `${file}:${l}`);
      }
      groups = [];
      anm = [];
      pltt = [];
    }
  });
}
const refTable = (table: Map<number, Map<number, string[]>>) =>
  [...table.keys()].sort((a, b) => a - b).map((g) => {
    const items = [...table.get(g)!.entries()].sort((a, b) => a[0] - b[0]).map(([v, where]) => `[${hex4(v)}, ${JSON.stringify(where.join(", "))}]`);
    return `  ${hex4(g)}: [${items.join(", ")}],`;
  }).join("\n");

await Deno.writeTextFile(
  new URL("../particle_refs.ts", import.meta.url),
  `// This file is generated by tools/gen_tables.ts. Do not edit.

// パーティクルのグループID -> [定数名, 説明] (include/particle.h in boktai2 decomp)
export const PARTICLE_GROUP_NAMES: Record<number, [name: string, desc: string]> = {
${nameTable(particleGroups)}
};

// グループID -> ポーズ番号 -> [定数名, 説明] (include/constants/particle.h in boktai2 decomp)
export const PARTICLE_POSE_NAMES: Record<number, Record<number, [name: string, desc: string]>> = {
${poseLines.join("\n")}
};

// グループID -> [アニメファイルID, 同じ関数で使われている場所][] (ROM のデータからは決まらないのでソースから拾ったもの)
export const PARTICLE_ANIM_REFS: Record<number, [anim: number, where: string][]> = {
${refTable(ptclAnims)}
};

// グループID -> [OBJ の plttID, 同じ関数で Particle_SetPltt に渡されている場所][]
export const PARTICLE_PLTT_REFS: Record<number, [plttID: number, where: string][]> = {
${refTable(ptclPltts)}
};
`,
);

console.log(`${sprites.length} sprites, ${anims.length} anims, ${bgPltts.length} bg palettes, ${pairs.size} sprites with anims, ${bgPlttRefs.size} bg palettes referenced`);
