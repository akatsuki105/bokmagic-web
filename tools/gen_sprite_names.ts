// boktai2 decomp の include/constants/sprite.h から sprite_names.ts を作る
// e.g. deno run --allow-read --allow-write tools/gen_sprite_names.ts ~/Dev/GBA/ret/boktai2/boktai2

// BOKHASH (tools/hash.ts in boktai2 decomp), ここで使うのは ASCII だけ
const bokhash = (s: string): number => {
  let hash = 0;
  for (const byte of new TextEncoder().encode(s)) {
    hash = ((hash << 5) | (hash >>> 11)) & 0xFFFF;
    hash = (hash + byte) & 0xFFFF;
  }
  return hash;
};

const decomp = Deno.args[0];
if (!decomp) {
  console.error("usage: gen_sprite_names.ts <boktai2 decomp dir>");
  Deno.exit(1);
}

const src = await Deno.readTextFile(`${decomp}/include/constants/sprite.h`);
const lines: string[] = [];
const seen = new Set<number>();
for (const line of src.split("\n")) {
  const m = line.match(/^#define (SPRITE_\w+)\s+(0x[0-9A-Fa-f]+|BOKHASH\("([^"]+)"\))\s*(?:\/\/\s*(.*))?$/);
  if (!m) continue;
  const id = m[3] !== undefined ? bokhash(m[3]) : parseInt(m[2], 16);
  if (seen.has(id)) continue; // 先に書かれた方を採る
  seen.add(id);
  const desc = (m[4] ?? "").replace(/^0x[0-9A-Fa-f]{4},\s*/, ""); // BOKHASH の値の注記は除く
  lines.push(`  0x${id.toString(16).toUpperCase().padStart(4, "0")}: [${JSON.stringify(m[1])}, ${JSON.stringify(desc)}],`);
}

const out = `// This file is generated by tools/gen_sprite_names.ts. Do not edit.

// SpriteID -> [定数名, 説明] (include/constants/sprite.h in boktai2 decomp)
export const SPRITE_NAMES: Record<number, [name: string, desc: string]> = {
${lines.join("\n")}
};
`;
await Deno.writeTextFile(new URL("../sprite_names.ts", import.meta.url), out);
console.log(`${lines.length} names`);
